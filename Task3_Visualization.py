import pandas as pd
import matplotlib.pyplot as plt
data = pd.read_csv("Sales_data.csv")
print(data)
product_sales = data.groupby("Product")["Sales"].sum()
plt.bar(product_sales.index, product_sales.values)
plt.title("Product Wise Sales")
plt.xlabel("Product")
plt.ylabel("Total Sales")
plt.show()
category_sales = data.groupby("Category")["Sales"].sum()
plt.pie(category_sales.values, labels=category_sales.index, autopct="%1.1f%%")
plt.title("Category Wise Sales")
plt.show()
plt.hist(data["Sales"], bins=5)
plt.title("Sales Distribution")
plt.xlabel("Sales")
plt.ylabel("Frequency")
plt.show()
plt.scatter(data["Quantity"], data["Sales"])
plt.title("Quantity vs Sales")
plt.xlabel("Quantity")
plt.ylabel("Sales")
plt.show()
plt.plot(data["Product"], data["Sales"], marker="o")
plt.title("Product Sales Trend")
plt.xlabel("Product")
plt.ylabel("Sales")
plt.show()
