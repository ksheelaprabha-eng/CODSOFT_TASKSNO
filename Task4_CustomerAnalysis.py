import pandas as pd
data = pd.read_csv("customer_data.csv")
print("Customer Data:")
print(data)
print("Customer Statistics:")
print(data.describe())
print("Total Customers:")
print(len(data))
print("Average Customer Age:")
print(data["Age"].mean())
print("Total Purchase Amount:")
print(data["PurchaseAmount"].sum())
print("City Wise Purchase Amount:")
print(data.groupby("City")["PurchaseAmount"].sum())
print("Gender Wise Purchase Amount:")
print(data.groupby("Gender")["PurchaseAmount"].sum())
print("Customer Segmentation:")
data["CustomerType"] = data["PurchaseAmount"].apply(lambda x: "High Value" if x >= 6000 else "Regular")
print(data[["CustomerID", "PurchaseAmount", "CustomerType"]])
data.to_csv("customer_analysis_result.csv", index=False)
print("Customer Analysis Report Saved Successfully!")
