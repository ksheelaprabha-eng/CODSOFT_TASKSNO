import pandas as pd
data = pd.read_csv("sales_data.csv")
print(data)
print("Sales Statistics:")
print(data.describe())
print("Average Sales:")
print(data["Sales"].mean())
print("Total Sales:")
print(data["Sales"].sum())
print("Maximum Sales:")
print(data["Sales"].max())
print("Minimum Sales:")
print(data["Sales"].min())
print("product Wise Sales:")
print(data.groupby("Product")["Sales"].sum())
print("Sales Outliers:")
Q1 = data["Sales"].quantile(0.25)
Q3 = data["Sales"].quantile(0.75)
IQR = Q3 - Q1
outliers = data[(data["Sales"] < Q1 - 1.5 * IQR) | (data["Sales"] > Q3 + 1.5 * IQR)]
print(outliers)
print("Sales by City:")
print(data.groupby("City")["Sales"].sum())
print("EDA Summary:")
print("Total Sales:", data["Sales"].sum())
print("Best Selling Product:", data.groupby("Product")["Sales"].sum().idxmax())
print("Highest Sales City:", data.groupby("City")["Sales"].sum().idxmax())
